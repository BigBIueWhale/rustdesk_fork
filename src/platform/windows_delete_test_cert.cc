extern "C" BOOL DeleteRustDeskTestCertsW()
{
    bool ok = true;
    ok = delete_from_hive(HKEY_CURRENT_USER, L"") && ok;
    ok = delete_from_hive(HKEY_LOCAL_MACHINE, L"") && ok;
    ok = delete_from_all_user_hives() && ok;
    return ok ? TRUE : FALSE;
}
